def _resolve_product_line(agent_id: str) -> str:
    return PRODUCT_LINE_BY_AGENT.get(agent_id, "shared")


def get_all_agents_config(*, include_utility: bool = True) -> List[Dict[str, Any]]:
    """返回全部 Agent 配置（浅拷贝列表，供 API 过滤与序列化）。"""
    configs: List[Dict[str, Any]] = []
    for agent_id, cfg in AGENTS_CONFIG.items():
        if not include_utility and cfg.get("category") == "utility":
            continue
        item = dict(cfg)
        item["product_line"] = _resolve_product_line(agent_id)
        configs.append(item)
    return configs


def get_agent_config(agent_id: str) -> Optional[Dict[str, Any]]:
    """按 id 返回单个 Agent 配置；不存在则 None。"""
    # auto 与 juben_conductor 同一实现
    if agent_id == "auto":
        agent_id = "juben_conductor"
    cfg = AGENTS_CONFIG.get(agent_id)
    if cfg is None and agent_id == "juben_conductor":
        cfg = AGENTS_CONFIG.get("auto")
    if cfg is None:
        return None
    item = dict(cfg)
    item["product_line"] = _resolve_product_line(agent_id)
    return item


